    private void setupModernDesign() {
        // Estilo para botones
        styleButton(jButton2, new Color(46, 204, 113), Color.WHITE);
        styleButton(jButton1, new Color(231, 76, 60), Color.WHITE);
        
        // Estilo para campos de texto
        styleTextField(jTextField1);
        styleTextField(jTextField2);
        styleTextField(jTextField3);
        styleTextField(jTextField4);
        styleTextField(jTextField5);
        styleTextField(jTextField6);
        
        // Estilo para combobox
        styleComboBox(jComboBox1);
        styleComboBox(jComboBox2);
        
        // Configurar acciones de botones
        jButton1.addActionListener(new ActionListener() {
            @Override
            public void actionPerformed(ActionEvent e) {
                limpiarCampos();
            }
        });
        
        jButton2.addActionListener(new ActionListener() {
            @Override
            public void actionPerformed(ActionEvent e) {
                registrarProducto();
            }
        });
    }
    
    private void styleButton(JButton button, Color bgColor, Color fgColor) {
        button.setBackground(bgColor);
        button.setForeground(fgColor);
        button.setFocusPainted(false);
        button.setBorder(BorderFactory.createCompoundBorder(
            BorderFactory.createLineBorder(bgColor.darker(), 1),
            BorderFactory.createEmptyBorder(10, 20, 10, 20)
        ));
        button.setCursor(new Cursor(Cursor.HAND_CURSOR));
        
        // Efecto hover
        button.addMouseListener(new java.awt.event.MouseAdapter() {
            public void mouseEntered(java.awt.event.MouseEvent evt) {
                button.setBackground(bgColor.brighter());
            }
            public void mouseExited(java.awt.event.MouseEvent evt) {
                button.setBackground(bgColor);
            }
        });
    }
    
    private void styleTextField(JTextField textField) {
        textField.setBorder(BorderFactory.createCompoundBorder(
            BorderFactory.createLineBorder(new Color(189, 195, 199), 1),
            BorderFactory.createEmptyBorder(5, 10, 5, 10)
        ));
    }
    
    private void styleComboBox(JComboBox<String> comboBox) {
        comboBox.setBorder(BorderFactory.createCompoundBorder(
            BorderFactory.createLineBorder(new Color(189, 195, 199), 1),
            BorderFactory.createEmptyBorder(5, 10, 5, 10)
        ));
        comboBox.setBackground(Color.WHITE);
    }
    
    private void limpiarCampos() {
        jTextField1.setText("");
        jTextField2.setText("");
        jTextField3.setText("");
        jTextField4.setText("");
        jTextField5.setText("");
        jTextField6.setText("");
        jComboBox1.setSelectedIndex(0);
        jComboBox2.setSelectedIndex(0);
        jDateChooser1.setDate(null);
        jTextField1.requestFocus();
    }
    
    private void registrarProducto() {
        // Validar campos
        if (jTextField1.getText().trim().isEmpty() || 
            jTextField2.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, 
                "Debe completar los campos obligatorios (Código y Nombre)", 
                "Validación", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        // Agregar a la tabla
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.addRow(new Object[]{
            jTextField1.getText(),
            jTextField2.getText(),
            jComboBox1.getSelectedItem(),
            jComboBox2.getSelectedItem(),
            jTextField6.getText(),
            jTextField5.getText(),
            jTextField4.getText(),
            jDateChooser1.getDate() != null ? 
                new java.text.SimpleDateFormat("yyyy-MM-dd").format(jDateChooser1.getDate()) : "N/A"
        });
        
        JOptionPane.showMessageDialog(this, 
            "Producto registrado exitosamente", 
            "Éxito", JOptionPane.INFORMATION_MESSAGE);
        
        limpiarCampos();
    }

